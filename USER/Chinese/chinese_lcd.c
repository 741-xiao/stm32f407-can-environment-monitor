extern u16 BRUSH_COLOR;
extern u16 BACK_COLOR;

/* UTF-8 labels use a small embedded subset; no external font ROM is needed. */
void LCD_TextUTF8(u16 x, u16 y, const char *text)
{
    const unsigned char *p = (const unsigned char *)text;
    unsigned int i;
    u16 code;
    u8 row, col;
    while (*p && y + 24U <= lcd_height) {
        if (*p < 128U) {
            if (x + 8U > lcd_width) break;
            LCD_DisplayChar(x, (u16)(y + 4U), *p++, 16U);
            x += 8U;
        } else if ((*p & 0xF0U) == 0xE0U && p[1] && p[2] &&
                   (p[1] & 0xC0U) == 0x80U && (p[2] & 0xC0U) == 0x80U) {
            if (x + 24U > lcd_width) break;
            code = (u16)(((p[0] & 15U) << 12) | ((p[1] & 63U) << 6) | (p[2] & 63U));
            for (i = 0U; i < sizeof(app_glyphs) / sizeof(app_glyphs[0]); i++)
                if (app_glyphs[i].code == code) break;
            if (i < sizeof(app_glyphs) / sizeof(app_glyphs[0])) {
                for (row = 0U; row < 24U; row++)
                    for (col = 0U; col < 24U; col++)
                        LCD_Color_DrawPoint((u16)(x + col), (u16)(y + row),
                            app_glyphs[i].rows[row] & (0x800000UL >> col) ? BRUSH_COLOR : BACK_COLOR);
            } else LCD_DisplayChar(x, (u16)(y + 4U), '?', 16U);
            p += 3;
            x += 24U;
        } else { p++; }
    }
}

