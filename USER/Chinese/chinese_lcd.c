void LCD_DisplayChinese(u16 x, u16 y, u8 index)
{
    u8 row;
    u8 col;
    u32 row_data;

    if (index >= (sizeof(lcd_hanzi) / sizeof(lcd_hanzi[0])))
    {
        return;
    }
    for (row = 0U; row < 26U; row++)
    {
        for (col = 0U; col < 26U; col++)
        {
            if ((row > 0U) && (row < 25U) && (col > 0U) && (col < 25U))
            {
                row_data = lcd_hanzi[index][row - 1U];
                if ((row_data & ((u32)0x800000U >> (col - 1U))) != 0U)
                {
                    LCD_Color_DrawPoint((u16)(x + col), (u16)(y + row), BRUSH_COLOR);
                }
                else
                {
                    LCD_Color_DrawPoint((u16)(x + col), (u16)(y + row), BACK_COLOR);
                }
            }
            else
            {
                LCD_Color_DrawPoint((u16)(x + col), (u16)(y + row), BACK_COLOR);
            }
        }
    }
}
